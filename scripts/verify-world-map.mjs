import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from 'playwright';
import {loadMapModel} from './load-map-model.mjs';
const model=await loadMapModel();
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
await context.addInitScript(seed=>{if(!localStorage.getItem('punjab-studio-regional-v2'))localStorage.setItem('punjab-studio-regional-v2',JSON.stringify(seed));},model.initial);
const page=await context.newPage();page.setDefaultTimeout(120000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const requested=[];page.on('request',r=>{if(r.url().includes('/data/'))requested.push(r.url());});
try{
  await page.goto(process.env.MAP_TEST_URL||'http://127.0.0.1:4546/',{waitUntil:'domcontentloaded'});
  await page.locator('.gl-host[aria-busy=false]').waitFor();
  await page.getByRole('button',{name:'Open world map',exact:true}).click();
  await page.getByLabel('World country',{exact:true}).waitFor();
  await page.locator('.gl-host[aria-busy=false]').waitFor();
  assert.ok(requested.some(u=>u.includes('/world-region.geojson')));
  assert.ok(requested.some(u=>u.includes('/world-province.geojson')));
  assert.ok(Number((await page.locator('.zoom-controls span').innerText()).replace('z','').trim())<1,'Whole-world desktop fit allows space around the globe');
  assert.equal(await page.getByLabel('World country',{exact:true}).locator('option').count(),219);
  await fs.mkdir('outputs/world-map',{recursive:true});
  await page.screenshot({path:'outputs/world-map/world.png'});
  await page.getByLabel('World country',{exact:true}).selectOption('world-c-gbr');
  await page.locator('.gl-host[aria-busy=false]').waitFor();
  assert.equal(await page.getByLabel('World first-level division',{exact:true}).locator('option').count(),5);
  await page.getByLabel('World administrative level',{exact:true}).selectOption('country');
  await page.locator('.gl-host[aria-busy=false]').waitFor();
  const canvas=page.locator('.gl-host canvas');
  const box=await canvas.boundingBox();assert.ok(box);
  await page.mouse.click(box.x+box.width*.5,box.y+box.height*.5);
  // Verify a country selection through the search UI, independent of label placement.
  await page.getByRole('tab',{name:'Areas',exact:true}).click();
  await page.getByRole('searchbox',{name:'Find an area',exact:true}).fill('United Kingdom');
  const card=page.locator('[data-area="world-c-gbr"]');
  await card.locator('.area-name').click();
  const painted=await page.evaluate(()=>JSON.parse(localStorage.getItem('punjab-studio-regional-v2')));
  assert.ok(painted.fills['world-c-gbr']);
  await page.getByRole('button',{name:'Export map',exact:true}).click();
  await page.getByRole('button',{name:'SVG',exact:true}).click();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download SVG',exact:true}).click();
  const file=await download;assert.equal(file.suggestedFilename(),'world-countries-first-level-divisions.svg');
  await file.saveAs('outputs/world-map/united-kingdom.svg');
  const svg=await fs.readFile('outputs/world-map/united-kingdom.svg','utf8');
  assert.ok(!/NaN|Infinity/.test(svg));assert.match(svg,/geoBoundaries/);assert.match(svg,/data-area="world-c-gbr"/);
  await page.keyboard.press('Escape');
  await page.reload({waitUntil:'domcontentloaded'});
  await page.getByLabel('World country',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('World country',{exact:true}).inputValue(),'world-c-gbr');
  assert.equal(await page.getByLabel('World administrative level',{exact:true}).inputValue(),'country');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Open world map',exact:true}).click();
  await page.getByLabel('World country',{exact:true}).waitFor();
  await page.locator('.gl-host[aria-busy=false]').waitFor();
  assert.ok(Number((await page.locator('.zoom-controls span').innerText()).replace('z','').trim())<0,'Whole world fits the narrow mobile viewport');
  await page.screenshot({path:'outputs/world-map/mobile.png'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth)<=392);
  assert.deepEqual(errors,[]);
  console.log('Verified world rendering, both administrative layers, four UK divisions, country painting/search, finite labeled SVG download with attribution, autosave/reload and mobile controls without browser errors.');
}finally{await browser.close();}
